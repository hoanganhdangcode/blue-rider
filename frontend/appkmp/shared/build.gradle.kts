abstract class GenerateBuildEnvTask: DefaultTask(){
    @get:InputFile
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val envFile: RegularFileProperty

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val source = envFile.get().asFile
        val json = groovy.json.JsonSlurper().parse(source) as Map<*, *>
        fun string(key: String): String =
            json[key] as? String ?: throw GradleException("'$key' (String) is missing or invalid in ${source.name}")

        fun boolean(key: String): Boolean =
            json[key] as? Boolean ?: throw GradleException("'$key' (Boolean) is missing or invalid in ${source.name}")

        val content = """                                                                                                                                                                                                        
              |// Generated by :shared:generateBuildEnv from ${source.name} — DO NOT EDIT                                                                                                                                          
              |package $PACKAGE_NAME                                                                                                                                                                                               
              |                                                                                                                                                                                                                    
              |internal object BuildEnv {                                                                                                                                                                                          
              |    const val ENVIRONMENT: String = ${string("environment").toKotlinStringLiteral()}                                                                                                                                
              |    const val BASE_URL: String = ${string("baseUrl").toKotlinStringLiteral()}                                                                                                                                       
              |    const val ENABLE_HTTP_LOG: Boolean = ${boolean("enableHttpLog")}                                                                                                                                                
              |    const val DEBUG: Boolean = ${boolean("debug")}                                                                                                                                                                  
              |}                                                                                                                                                                                                                   
              |                                                                                                                                                                                                                    
          """.trimMargin()

        val outDir = outputDir.get().asFile
        outDir.deleteRecursively()
        val outFile = outDir.resolve(PACKAGE_NAME.replace('.', '/')).resolve("BuildEnv.kt")
        outFile.parentFile.mkdirs()
        outFile.writeText(content)
    }
    private fun String.toKotlinStringLiteral(): String {
        val escaped = this
            .replace("\\", "\\\\")
            .replace("\"", "\\\"")
            .replace("$", "\\$")
            .replace("\n", "\\n")
        return "\"$escaped\""
    }

    private companion object {
        const val PACKAGE_NAME = "com.rideplatform.blueride.core.config"
    }


}